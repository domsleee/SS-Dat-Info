//! Start/finish-line crossing detection for recordings (game-awareness 1.6 +
//! 1.7: "the timer under From: should be from when it crosses the start
//! line", "if the player crosses the finish line during record, the
//! recording should stop").
//!
//! The game's race timer starts/ends at TRIGGER PLANES (Start_Point /
//! Finish_Point markers), already extracted offline into
//! `analyze/src/LevelData/levelData.json`; the tables below are generated
//! from it (`TAS/tools/gen_start_lines.py`, `gen_finish_lines.py`).
//!
//! Geometry: on all nine tracks the course coordinates rise monotonically in
//! BOTH y and z from start to finish, with z the dominant axis (Δz ≈ +2200 vs
//! Δy ≈ +1100 over a run), so a crossing is detected as "z rises past the
//! trigger's z" gated to the plane's lateral (x) extent. Tracks with several
//! points for one line (a wide line, or course variants) cross on ANY point;
//! the start picks the point nearest the spawn first.

/// Trigger plane half-extent (engine constant, from the line-geometry RE).
const PLANE_RADIUS: f32 = 90.5;

